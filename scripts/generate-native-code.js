#!/usr/bin/env node

/**
 * Auto-generate native C++ code from operator definitions
 * This script parses the C++ operator files and generates:
 * - fastled_operators.h (operator declarations)
 * - operator_registry.cpp (operator registry)
 * - wasm_interface.cpp (WASM interface)
 * - Updates Makefile to use dynamic file listing
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const NATIVE_DIR = path.join(__dirname, '../src/native');
const OPERATORS_DIR = path.join(NATIVE_DIR, 'operators');

// Parse operator information from C++ files
function parseOperatorInfo(filePath) {
    const content = fs.readFileSync(filePath, 'utf8');
    const operatorName = path.basename(filePath, '.cpp');
    
    // Extract display name from comments or generate from filename
    const displayNameMatch = content.match(/\/\/\s*(.+?)\s+operator/i);
    const displayName = displayNameMatch ? displayNameMatch[1] : 
        operatorName.split('_').map(word => 
            word.charAt(0).toUpperCase() + word.slice(1)
        ).join(' ');
    
    // Find parameter array definition
    const paramArrayRegex = new RegExp(`(?:static\\s+)?const OperatorParameter ${operatorName}_params\\[\\]\\s*=\\s*{([\\s\\S]*?)};`, 's');
    const match = content.match(paramArrayRegex);
    
    let paramCount = 0;
    if (match) {
        // Count parameters by counting opening braces
        const paramContent = match[1];
        paramCount = (paramContent.match(/{/g) || []).length;
    }
    
    return {
        operatorName,
        displayName,
        paramCount,
        functionName: `${operatorName}_operator`,
        paramsArrayName: `${operatorName}_params`
    };
}

// Generate fastled_operators.h
function generateHeaderFile(operators) {
    const functionDeclarations = operators.map(op => 
        `    void ${op.functionName}(OperatorContext* ctx);`
    ).join('\n');
    
    const paramDeclarations = operators.map(op =>
        `extern const OperatorParameter ${op.paramsArrayName}[];`
    ).join('\n');

    return `// Auto-generated operator header file
// DO NOT EDIT - Generated by scripts/generate-native-code.js
// Run 'npm run wasm:generate' to regenerate this file
//
// This file provides the main header for FastLED operators with 2D buffer support.
// Operator function declarations and parameter arrays are auto-generated from 
// the individual operator source files.

#ifndef FASTLED_OPERATORS_H
#define FASTLED_OPERATORS_H

#include <stdint.h>
#include <stdbool.h>
#include <cmath>

#if defined(__EMSCRIPTEN__) || defined(NATIVE_BUILD)
// WASM or native test build - provide essential FastLED-compatible types and functions
#ifdef __EMSCRIPTEN__
#include <emscripten.h>
#endif

// CRGB color type (compatible with FastLED)
struct CRGB {
    uint8_t r, g, b;
    
    CRGB() : r(0), g(0), b(0) {}
    CRGB(uint8_t red, uint8_t green, uint8_t blue) : r(red), g(green), b(blue) {}
    
    // Assignment from CHSV
    CRGB& operator=(const struct CHSV& hsv);
};

// CHSV color type (compatible with FastLED)
struct CHSV {
    uint8_t h, s, v;
    
    CHSV() : h(0), s(0), v(0) {}
    CHSV(uint8_t hue, uint8_t sat, uint8_t val) : h(hue), s(sat), v(val) {}
    
    // Conversion to CRGB
    operator CRGB() const;
};

// FastLED-compatible timing functions
uint8_t beat8(uint16_t beats_per_minute, uint32_t timebase = 0);
uint16_t beat16(uint16_t beats_per_minute, uint32_t timebase = 0);

// FastLED-compatible noise functions
uint8_t inoise8(uint16_t x, uint16_t y = 0, uint16_t z = 0);
uint16_t inoise16(uint16_t x, uint16_t y = 0, uint16_t z = 0);

// FastLED-compatible math functions
uint8_t scale8(uint8_t i, uint8_t scale);
uint16_t scale16(uint16_t i, uint16_t scale);
uint8_t sin8(uint8_t theta);
uint8_t cos8(uint8_t theta);
uint8_t random8();
uint8_t random8(uint8_t max);
uint16_t random16();
uint16_t random16(uint16_t max);
uint8_t qadd8(uint8_t a, uint8_t b);
uint8_t qsub8(uint8_t a, uint8_t b);
uint8_t dim8_raw(uint8_t x);
uint8_t brighten8_raw(uint8_t x);

// FastLED-compatible blend functions
CRGB blend(const CRGB& a, const CRGB& b, uint8_t amount);

#else
// ESP32 build - use standard FastLED
#include <FastLED.h>
#endif

// Operator context structure with 2D buffer
typedef struct {
    CRGB* color_buffer;       // 2D color buffer (width * height)
    CRGB* input_buffer1;      // First input buffer (for blend operations)
    CRGB* input_buffer2;      // Second input buffer (for blend operations)
    uint32_t width;           // Buffer width in pixels
    uint32_t height;          // Buffer height in pixels
    uint32_t timestamp_ms;    // Current timestamp in milliseconds
    uint32_t delta_time_ms;   // Time since last call in milliseconds
    bool is_starting;         // True if operator is being initialized
    bool is_ending;           // True if operator is being cleaned up
    float* parameters;        // Array of parameter values
    uint32_t param_count;     // Number of parameters
} OperatorContext;

// Parameter definition structure
typedef struct {
    const char* name;
    const char* label;
    const char* type;         // "float", "int", "color", "select"
    float default_value;
    float min_value;
    float max_value;
    const char** options;     // For select type parameters
    uint32_t option_count;
} OperatorParameter;

// Operator definition structure
typedef struct {
    const char* name;
    const char* type;
    const OperatorParameter* parameters;
    uint32_t param_count;
    void (*operator_func)(OperatorContext* ctx);
} OperatorDefinition;

// Auto-generated operator function declarations
extern "C" {
${functionDeclarations}
}

// Auto-generated operator parameter array declarations
${paramDeclarations}

// Operator registry (defined in operator_registry.cpp)
extern const OperatorDefinition OPERATOR_DEFINITIONS[];
extern const uint32_t OPERATOR_COUNT;

// Utility functions for 2D buffer access
inline void set_pixel(OperatorContext* ctx, uint32_t x, uint32_t y, CRGB color) {
    if (x < ctx->width && y < ctx->height) {
        ctx->color_buffer[y * ctx->width + x] = color;
    }
}

inline CRGB get_pixel(OperatorContext* ctx, uint32_t x, uint32_t y) {
    if (x < ctx->width && y < ctx->height) {
        return ctx->color_buffer[y * ctx->width + x];
    }
    return CRGB(0, 0, 0);
}

inline CRGB get_input1_pixel(OperatorContext* ctx, uint32_t x, uint32_t y) {
    if (ctx->input_buffer1 && x < ctx->width && y < ctx->height) {
        return ctx->input_buffer1[y * ctx->width + x];
    }
    return CRGB(0, 0, 0);
}

inline CRGB get_input2_pixel(OperatorContext* ctx, uint32_t x, uint32_t y) {
    if (ctx->input_buffer2 && x < ctx->width && y < ctx->height) {
        return ctx->input_buffer2[y * ctx->width + x];
    }
    return CRGB(0, 0, 0);
}

// Utility function to get normalized coordinates (0.0 to 1.0)
inline float get_normalized_x(OperatorContext* ctx, uint32_t x) {
    return (float)x / (float)(ctx->width - 1);
}

inline float get_normalized_y(OperatorContext* ctx, uint32_t y) {
    return (float)y / (float)(ctx->height - 1);
}

// Clear the entire buffer
inline void clear_buffer(OperatorContext* ctx, CRGB color = CRGB(0, 0, 0)) {
    uint32_t total_pixels = ctx->width * ctx->height;
    for (uint32_t i = 0; i < total_pixels; i++) {
        ctx->color_buffer[i] = color;
    }
}

#endif // FASTLED_OPERATORS_H
`;
}

// Generate operator_registry.cpp
function generateRegistryFile(operators) {
    const registryEntries = operators.map(op =>
        `    {"${op.displayName}", "${op.operatorName}", ${op.paramsArrayName}, ${op.paramCount}, ${op.functionName}}`
    ).join(',\n');

    return `// Auto-generated operator registry
// DO NOT EDIT - Generated by scripts/generate-native-code.js
// Run 'npm run wasm:generate' to regenerate this file
//
// This file contains the registry of all available FastLED operators.
// The registry is automatically built from the individual operator source files.

#include "fastled_operators.h"

// Auto-generated operator registry - parameters are defined alongside their functions
const OperatorDefinition OPERATOR_DEFINITIONS[] = {
${registryEntries}
};

const uint32_t OPERATOR_COUNT = sizeof(OPERATOR_DEFINITIONS) / sizeof(OperatorDefinition);
`;
}

// Generate wasm_interface.cpp
function generateWasmInterface(operators) {
    const callFunctions = operators.map(op => `
EMSCRIPTEN_KEEPALIVE
void call_${op.operatorName}_operator(OperatorContext* ctx) {
    if (!ctx) return;
    ${op.functionName}(ctx);
}`).join('\n');

    const exportedFunctions = operators.map(op => `"_call_${op.operatorName}_operator"`).join(', ');

    return `// Auto-generated WASM interface
// DO NOT EDIT - Generated by scripts/generate-native-code.js
// Run 'npm run wasm:generate' to regenerate this file
//
// This file provides the WASM interface for FastLED operators.
// Each operator gets a corresponding call_X_operator function that can be invoked from JavaScript.

#include "fastled_operators.h"
#include <emscripten.h>
#include <cstring>
#include <cstdlib>

static OperatorContext* g_context = nullptr;

extern "C" {

EMSCRIPTEN_KEEPALIVE
OperatorContext* create_context(uint32_t width, uint32_t height) {
    OperatorContext* ctx = (OperatorContext*)malloc(sizeof(OperatorContext));
    if (!ctx) return nullptr;
    
    // Allocate 2D color buffer
    uint32_t total_pixels = width * height;
    ctx->color_buffer = (CRGB*)malloc(total_pixels * sizeof(CRGB));
    if (!ctx->color_buffer) {
        free(ctx);
        return nullptr;
    }
    
    // Initialize context
    ctx->input_buffer1 = nullptr;
    ctx->input_buffer2 = nullptr;
    ctx->width = width;
    ctx->height = height;
    ctx->timestamp_ms = 0;
    ctx->delta_time_ms = 0;
    ctx->is_starting = true;
    ctx->is_ending = false;
    ctx->parameters = nullptr;
    ctx->param_count = 0;
    
    // Clear the buffer to black
    clear_buffer(ctx, CRGB(0, 0, 0));
    
    g_context = ctx;
    return ctx;
}

EMSCRIPTEN_KEEPALIVE
void destroy_context(OperatorContext* ctx) {
    if (!ctx) return;
    
    if (ctx->color_buffer) {
        free(ctx->color_buffer);
    }
    if (ctx->input_buffer1) {
        free(ctx->input_buffer1);
    }
    if (ctx->input_buffer2) {
        free(ctx->input_buffer2);
    }
    if (ctx->parameters) {
        free(ctx->parameters);
    }
    
    free(ctx);
    
    if (g_context == ctx) {
        g_context = nullptr;
    }
}

EMSCRIPTEN_KEEPALIVE
void set_timing(OperatorContext* ctx, uint32_t timestamp_ms, uint32_t delta_time_ms) {
    if (!ctx) return;
    ctx->timestamp_ms = timestamp_ms;
    ctx->delta_time_ms = delta_time_ms;
    ctx->is_starting = false; // Clear starting flag after first timing update
}

EMSCRIPTEN_KEEPALIVE
void set_parameters(OperatorContext* ctx, float* params, uint32_t param_count) {
    if (!ctx) return;
    
    // Free existing parameters
    if (ctx->parameters) {
        free(ctx->parameters);
        ctx->parameters = nullptr;
        ctx->param_count = 0;
    }
    
    if (params && param_count > 0) {
        // Allocate new parameter array
        ctx->parameters = (float*)malloc(param_count * sizeof(float));
        if (ctx->parameters) {
            memcpy(ctx->parameters, params, param_count * sizeof(float));
            ctx->param_count = param_count;
        }
    }
}

EMSCRIPTEN_KEEPALIVE
uint8_t* get_output_buffer(OperatorContext* ctx) {
    if (!ctx || !ctx->color_buffer) return nullptr;
    
    // Return pointer to the raw RGB data
    return (uint8_t*)ctx->color_buffer;
}

EMSCRIPTEN_KEEPALIVE
uint32_t get_buffer_size(OperatorContext* ctx) {
    if (!ctx) return 0;
    return ctx->width * ctx->height * 3; // 3 bytes per pixel (RGB)
}

// Auto-generated operator call functions
${callFunctions}

} // extern "C"

// Note: Exported functions for Emscripten build:
// [${exportedFunctions}, "_create_context", "_destroy_context", "_set_timing", "_set_parameters", "_get_output_buffer", "_get_buffer_size", "_malloc", "_free"]
`;
}

// Update Makefile to use dynamic file listing and auto-generated exports
function updateMakefile(operators) {
    const makefilePath = path.join(NATIVE_DIR, 'Makefile');
    let content = fs.readFileSync(makefilePath, 'utf8');
    
    // Replace hardcoded SOURCES with dynamic listing (but not FASTLED_SOURCES line)
    content = content.replace(
        /^SOURCES = .*$/m,
        'SOURCES = operator_registry.cpp $(wildcard operators/*.cpp) $(FASTLED_SOURCES)'
    );
    
    // Replace hardcoded WASM_SOURCES with dynamic listing
    content = content.replace(
        /^WASM_SOURCES = .*$/m,
        'WASM_SOURCES = operator_registry.cpp $(wildcard operators/*.cpp) wasm_interface.cpp $(FASTLED_SOURCES)'
    );
    
    // Generate auto-generated exported functions list
    const exportedFunctions = [
        '"_create_context"', '"_destroy_context"', '"_set_timing"', '"_set_parameters"',
        '"_get_output_buffer"', '"_get_buffer_size"', '"_malloc"', '"_free"',
        ...operators.map(op => `"_call_${op.operatorName}_operator"`)
    ];
    
    // Replace hardcoded EXPORTED_FUNCTIONS with auto-generated list
    const exportedFunctionsStr = `'[${exportedFunctions.join(', ')}]'`;
    content = content.replace(
        /-s EXPORTED_FUNCTIONS='[^']*'/,
        `-s EXPORTED_FUNCTIONS=${exportedFunctionsStr}`
    );
    
    // Add auto-generation note
    if (!content.includes('# Auto-generated Makefile')) {
        content = `# Auto-generated Makefile - some parts generated by scripts/generate-native-code.js
${content}`;
    }
    
    return content;
}

// Main function
function main() {
    console.log('🔧 Generating native C++ code from operator definitions...');
    
    // Find all operator files
    const operatorFiles = fs.readdirSync(OPERATORS_DIR)
        .filter(file => file.endsWith('.cpp'))
        .map(file => path.join(OPERATORS_DIR, file));
    
    if (operatorFiles.length === 0) {
        console.error('❌ No operator files found in', OPERATORS_DIR);
        process.exit(1);
    }
    
    // Parse operator information
    const operators = operatorFiles.map(parseOperatorInfo).sort((a, b) => 
        a.operatorName.localeCompare(b.operatorName)
    );
    
    console.log(`📋 Found ${operators.length} operators:`, operators.map(op => op.operatorName).join(', '));
    
    // Generate files
    const headerContent = generateHeaderFile(operators);
    const registryContent = generateRegistryFile(operators);
    const wasmContent = generateWasmInterface(operators);
    const makefileContent = updateMakefile(operators);
    
    // Write files
    fs.writeFileSync(path.join(NATIVE_DIR, 'fastled_operators.h'), headerContent);
    fs.writeFileSync(path.join(NATIVE_DIR, 'operator_registry.cpp'), registryContent);
    fs.writeFileSync(path.join(NATIVE_DIR, 'wasm_interface.cpp'), wasmContent);
    fs.writeFileSync(path.join(NATIVE_DIR, 'Makefile'), makefileContent);
    
    console.log('✅ Generated native C++ files:');
    console.log('   - fastled_operators.h');
    console.log('   - operator_registry.cpp');
    console.log('   - wasm_interface.cpp');
    console.log('   - Updated Makefile');
    
    // Extract exported functions for reference
    const exportedFunctions = [
        '"_create_context"', '"_destroy_context"', '"_set_timing"', '"_set_parameters"',
        '"_get_output_buffer"', '"_get_buffer_size"', '"_malloc"', '"_free"',
        ...operators.map(op => `"_call_${op.operatorName}_operator"`)
    ];
    
    console.log('\n📤 WASM exported functions:');
    console.log('   ', exportedFunctions.join(', '));
}

if (import.meta.url === `file://${process.argv[1]}`) {
    main();
} 